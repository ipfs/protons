import { expect } from 'aegir/chai'
import { reader, writer } from '../src/index.ts'

// negative values below -(2^53 - 1) whose low 32 bits are zero used to lose
// the two's-complement carry into the high word and encode as value - 2^32
describe('negative 64-bit values', () => {
  const cases: Record<'int64' | 'sint64' | 'sfixed64', Array<[bigint, number[]]>> = {
    int64: [
      [-(2n ** 53n), [0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0xf0, 0xff, 0x01]],
      [-(2n ** 53n + 2n ** 32n), [0x80, 0x80, 0x80, 0x80, 0xf0, 0xff, 0xff, 0xef, 0xff, 0x01]],
      [-(2n ** 60n), [0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0xf0, 0x01]],
      [-(2n ** 63n - 2n ** 32n), [0x80, 0x80, 0x80, 0x80, 0x90, 0x80, 0x80, 0x80, 0x80, 0x01]],
      [-(2n ** 63n), [0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x01]],
      [-(2n ** 53n + 1n), [0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xef, 0xff, 0x01]]
    ],
    sint64: [
      [-(2n ** 53n), [0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x1f]],
      [-(2n ** 53n + 2n ** 32n), [0xff, 0xff, 0xff, 0xff, 0x9f, 0x80, 0x80, 0x20]],
      [-(2n ** 60n), [0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x1f]],
      [-(2n ** 63n - 2n ** 32n), [0xff, 0xff, 0xff, 0xff, 0xdf, 0xff, 0xff, 0xff, 0xff, 0x01]],
      [-(2n ** 63n), [0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x01]],
      [-(2n ** 53n + 1n), [0x81, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x20]]
    ],
    sfixed64: [
      [-(2n ** 53n), [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xe0, 0xff]],
      [-(2n ** 53n + 2n ** 32n), [0x00, 0x00, 0x00, 0x00, 0xff, 0xff, 0xdf, 0xff]],
      [-(2n ** 60n), [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xf0]],
      [-(2n ** 63n - 2n ** 32n), [0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x80]],
      [-(2n ** 63n), [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x80]],
      [-(2n ** 53n + 1n), [0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xdf, 0xff]]
    ]
  }

  for (const method of ['int64', 'sint64', 'sfixed64'] as const) {
    for (const [value, bytes] of cases[method]) {
      it(`should encode ${method} ${value}`, () => {
        const w = writer()
        w[method](value)

        expect(w.finish()).to.equalBytes(bytes)
      })

      it(`should round trip ${method} ${value}`, () => {
        const w = writer()
        w[method](value)

        expect(reader(w.finish())[method]()).to.equal(value)
      })
    }
  }
})
